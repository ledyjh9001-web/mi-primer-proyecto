const makeWave = (seed: number): number[] => {
  const bars: number[] = [];
  for (let i = 0; i < 48; i++) {
    const v =
      0.28 +
      0.65 *
        Math.abs(
          Math.sin(i * 0.43 + seed * 1.7) * Math.cos(i * 0.19 - seed * 0.8)
        );
    bars.push(Number(Math.min(0.98, Math.max(0.18, v)).toFixed(2)));
  }
  return bars;
};

